    private void CarsOnRentTbMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CarsOnRentTbMouseClicked
        DefaultTableModel model = (DefaultTableModel)CarsOnRentTb.getModel();
        int MyIndex = CarsOnRentTb.getSelectedRow();
        

        RentIDTb.setText(model.getValueAt(MyIndex, 0).toString());
        RegNumTb.setText(model.getValueAt(MyIndex, 1).toString());
        
        // 2. LOGIKA HITUNG DENDA OTOMATIS
        try {
            String dateInString = model.getValueAt(MyIndex, 4).toString(); 
            java.util.Date expectedDate = java.sql.Date.valueOf(dateInString);
            
            java.util.Date actualDate = ReturnDate.getDate();
            
            long diff = actualDate.getTime() - expectedDate.getTime();
            
            long diffDays = java.util.concurrent.TimeUnit.DAYS.convert(diff, java.util.concurrent.TimeUnit.MILLISECONDS);

            if (diffDays > 0) {

                DelayTb.setText(String.valueOf(diffDays));
                

                int fine = (int) diffDays * 1000; //Denda nya
                FeeTb1.setText(String.valueOf(fine));
            } else {
                // Kalo Tepat Waktu atau Lebih Cepat
                DelayTb.setText("0");
                FeeTb1.setText("0");
            }
            DisplayRentals(); 
            DisplayReturns();
            
        } catch (Exception e) {
            e.printStackTrace();
            DelayTb.setText("0");
            FeeTb1.setText("0");
        }
    }//GEN-LAST:event_CarsOnRentTbMouseClicked

