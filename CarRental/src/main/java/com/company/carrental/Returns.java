    private void ReturnBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ReturnBtnActionPerformed
        if(RentIDTb.getText().isEmpty() || RegNumTb.getText().isEmpty() || DelayTb.getText().isEmpty() || FeeTb1.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Data belum lengkap!");
        } else {
            try {
                Connection con = DBConnection.connect();
                // Catatan: RetId otomatis (Auto Increment), jadi tidak perlu ditulis
                String sql = "INSERT INTO returncar(Registration, Customer, ReturnDate, Delay, Fine) VALUES(?,?,?,?,?)";
                PreparedStatement pst = con.prepareStatement(sql);
                
                pst.setString(1, RegNumTb.getText());
                
                // Mengambil nama customer dari Tabel Sewa yang sedang dipilih
                DefaultTableModel model = (DefaultTableModel)CarsOnRentTb.getModel();
                int MyIndex = CarsOnRentTb.getSelectedRow();
                String CustName = model.getValueAt(MyIndex, 2).toString(); // Asumsi kolom ke-3 adalah Customer Name
                pst.setString(2, CustName);

                java.sql.Date sqlReturnDate = new java.sql.Date(ReturnDate.getDate().getTime());
                pst.setDate(3, sqlReturnDate);
                
                pst.setInt(4, Integer.valueOf(DelayTb.getText()));
                pst.setInt(5, Integer.valueOf(FeeTb1.getText()));
                
                pst.executeUpdate();
                //Update Status
                String updateCarQuery = "UPDATE carregistration SET available='Available' WHERE car_no='" + RegNumTb.getText() + "'";
                Statement st = con.createStatement();
                st.executeUpdate(updateCarQuery);
                //Delete rental yang udah berubah status
                String deleteRentQuery = "DELETE FROM rental WHERE rent_id='" + RentIDTb.getText() + "'";
                Statement st2 = con.createStatement();
                st2.executeUpdate(deleteRentQuery);

                JOptionPane.showMessageDialog(this, "Mobil Berhasil Dikembalikan!");
                
                DisplayRentals();
                DisplayReturns();
                
                Reset();

            } catch (Exception ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_ReturnBtnActionPerformed

