    private void GetCustomers() {
    try {
        Connection con = DBConnection.connect();
        Statement st = con.createStatement();
        String query = "SELECT * FROM customer";
        ResultSet rs = st.executeQuery(query);
        
        CusNameCb.removeAllItems(); 
        
        while(rs.next()){
            String cusName = rs.getString("NAME"); 
            CusNameCb.addItem(cusName);
        }
        
        con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}
    private void DisplayCarsOnRent() {
    try {
        Connection con = DBConnection.connect();
        Statement St = con.createStatement();
        ResultSet Rs = St.executeQuery("SELECT * FROM rental");
        
        java.sql.ResultSetMetaData rsmd = Rs.getMetaData();
        int columnCount = rsmd.getColumnCount();

        java.util.Vector<String> columns = new java.util.Vector<>();
        for (int i = 1; i <= columnCount; i++) {
            columns.add(rsmd.getColumnName(i));
        }
        
        java.util.Vector<java.util.Vector<Object>> data = new java.util.Vector<>();
        
        while (Rs.next()) {
            java.util.Vector<Object> row = new java.util.Vector<>();
            for (int i = 1; i <= columnCount; i++) {
                row.add(Rs.getObject(i));
            }
            data.add(row);
        }
        
        DefaultTableModel model = new DefaultTableModel(data, columns);
        RentTb.setModel(model); 
        
        con.close();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error menampilkan data rental: " + e.getMessage());
    }
}
    private void DisplayCars() {
        try {
            Connection con = DBConnection.connect();
            Statement St = con.createStatement();
            ResultSet Rs = St.executeQuery("SELECT * FROM carregistration");

            java.sql.ResultSetMetaData rsmd = Rs.getMetaData();
            int columnCount = rsmd.getColumnCount();

            java.util.Vector<String> columns = new java.util.Vector<>();
            for (int i = 1; i <= columnCount; i++) {
                columns.add(rsmd.getColumnName(i));
            }

            java.util.Vector<java.util.Vector<Object>> data = new java.util.Vector<>();

            while (Rs.next()) {
                java.util.Vector<Object> row = new java.util.Vector<>();
                for (int i = 1; i <= columnCount; i++) {
                    row.add(Rs.getObject(i));
                }
                data.add(row);
            }

            DefaultTableModel model = new DefaultTableModel(data, columns);
            CarTb.setModel(model);
            con.close(); 
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error menampilkan data: " + e.getMessage());
        }

    }

