    private void SaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveBtnActionPerformed
    if(RentIDTb.getText().isEmpty() || CusNameCb.getSelectedIndex() == -1 || RegNumTb.getText().isEmpty() || FeeTb.getText().isEmpty() || RentDate.getDate() == null || ReturnDate.getDate() == null){
        JOptionPane.showMessageDialog(this, "Masukin Data yang bener & lengkap");
    } else {
        try {
            String rentID = RentIDTb.getText();
            String regNum = RegNumTb.getText();
            String cusName = CusNameCb.getSelectedItem().toString();
            int rentFee = Integer.valueOf(FeeTb.getText());
            java.util.Date d1 = RentDate.getDate();
            java.util.Date d2 = ReturnDate.getDate();
            
            java.sql.Date sqlRentDate = new java.sql.Date(d1.getTime());
            java.sql.Date sqlReturnDate = new java.sql.Date(d2.getTime());
            // ----------------------------------

            Connection con = DBConnection.connect();
            PreparedStatement pst = con.prepareStatement("INSERT INTO rental(rent_id, car_reg, cus_name, fee, rent_date, return_date) VALUES(?,?,?,?,?,?)");

            pst.setString(1, rentID);
            pst.setString(2, regNum);
            pst.setString(3, cusName);
            pst.setInt(4, rentFee);
            pst.setDate(5, sqlRentDate);   
            pst.setDate(6, sqlReturnDate);

            pst.executeUpdate();
            
            String updateCarQuery = "UPDATE carregistration SET available='Booked' WHERE car_no='" + regNum + "'";
            Statement st = con.createStatement();
            st.executeUpdate(updateCarQuery);

            JOptionPane.showMessageDialog(this, "Data Rental Berhasil Disimpan!");
            
            DisplayCars();
            DisplayCarsOnRent();
            Reset();
            
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }
    }//GEN-LAST:event_SaveBtnActionPerformed

    private void EditBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditBtnActionPerformed
    if (RentIDTb.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data rental yang mau diedit");
    } else {
        try {
            Connection con = DBConnection.connect();
            String sql = "UPDATE rental SET car_reg=?, cus_name=?, fee=?, rent_date=?, return_date=? WHERE rent_id=?";
            PreparedStatement pst = con.prepareStatement(sql);
            
            java.sql.Date sqlRentDate = new java.sql.Date(RentDate.getDate().getTime());
            java.sql.Date sqlReturnDate = new java.sql.Date(ReturnDate.getDate().getTime());

            pst.setString(1, RegNumTb.getText());
            pst.setString(2, CusNameCb.getSelectedItem().toString());
            pst.setInt(3, Integer.valueOf(FeeTb.getText()));
            pst.setDate(4, sqlRentDate);
            pst.setDate(5, sqlReturnDate);
            pst.setString(6, RentIDTb.getText()); // Parameter ke-6 adalah rent_id untuk WHERE
            DisplayCars();
            DisplayCarsOnRent();
            int rowsAffected = pst.executeUpdate();
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Data Rental Berhasil Diupdate!");
                Reset();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal Update. Data tidak ditemukan.");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            ex.printStackTrace();
        }
    }
    }//GEN-LAST:event_EditBtnActionPerformed

